"""Ports of the ingestion application layer; implemented in infrastructure/."""
from __future__ import annotations

from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Iterable, Optional, Protocol


class ArtifactStorage(Protocol):
    """Checksums and atomic writes of local pipeline artifacts."""
    def sha256(self, path: Path | str) -> str: ...
    def write_json(self, path: Path | str, value: Any) -> None: ...
    def write_jsonl(self, path: Path, rows: Iterable[Any]) -> None: ...
    def write_gzip(self, target: Path, raw: bytes) -> None: ...


class DocumentStore(Protocol):
    """The insights PostgreSQL schema."""
    def initialize(self) -> None: ...
    def replace_csv_snapshot(self, directory: Path, manifest: dict) -> dict: ...
    def save_document(self, doc: dict, document_id: str, fingerprint: str) -> bool: ...
    def search(self, query: str, limit: int = 5, tags: Optional[list[str]] = None) -> list[dict]: ...
    def import_news_snapshot(self, root: Path, fingerprint: str, rows: list[tuple],
                             report: dict, audit: dict) -> dict: ...


class StagingDatabase(Protocol):
    """Disk-backed SQL scratch space for sorting and deduplicating large tables."""
    def open(self) -> AbstractContextManager[Any]: ...


class PdfReader(Protocol):
    version: str
    def open(self, path: Path) -> Any: ...


class OcrEngine(Protocol):
    def check(self, command: str, languages: str) -> str: ...
    def recognize(self, page: Any, command: str, languages: str, dpi: int, psm: int,
                  timeout: int) -> tuple[str, Optional[float]]: ...


class HttpFetcher(Protocol):
    def download(self, url: str, limit: int = 8_000_000) -> tuple[bytes, dict]: ...


class SectorClassifier(Protocol):
    settings: dict
    def predict(self, texts: list[str]) -> list[dict]: ...


class ChunkTagCache(Protocol):
    def load(self, config: str, texts: dict) -> dict: ...
    def save(self, config: str, text_hash: str, value: dict) -> None: ...
    def commit(self) -> None: ...


class ChunkTagCacheFactory(Protocol):
    def open(self, cache_dir: Path | str) -> AbstractContextManager[ChunkTagCache]: ...
